using ECommerce.Api.Contracts;
using ECommerce.Application.Common;
using Microsoft.AspNetCore.Mvc;

namespace ECommerce.Api.Extensions;

/// <summary>
/// Translates an application-layer <see cref="Result"/> into an HTTP response,
/// so controllers never contain status-code branching.
/// </summary>
public static class ResultExtensions
{
    public static IActionResult ToActionResult<TValue>(
        this Result<TValue> result,
        ControllerBase controller,
        Func<TValue, IActionResult>? onSuccess = null)
    {
        ArgumentNullException.ThrowIfNull(controller);

        if (result.IsFailure)
            return Failure(controller, result.Error);

        return onSuccess is not null
            ? onSuccess(result.Value)
            : controller.Ok(ApiResponse.Ok(result.Value));
    }

    public static IActionResult ToActionResult(
        this Result result,
        ControllerBase controller,
        IActionResult? onSuccess = null)
    {
        ArgumentNullException.ThrowIfNull(controller);

        if (result.IsFailure)
            return Failure(controller, result.Error);

        return onSuccess ?? controller.Ok(ApiResponse.Ok());
    }

    /// <param name="actionName">
    /// Target action on the same controller. Attribute-routed actions have no
    /// route name, so the location has to be generated by action name.
    /// </param>
    public static IActionResult CreatedAt<TValue>(
        this Result<TValue> result,
        ControllerBase controller,
        string actionName,
        object? routeValues = null)
    {
        ArgumentNullException.ThrowIfNull(controller);

        return result.IsFailure
            ? Failure(controller, result.Error)
            : controller.CreatedAtAction(
                actionName,
                ControllerName(controller),
                routeValues,
                ApiResponse.Ok(result.Value));
    }

    /// <summary>
    /// MVC matches the controller by name without the <c>Controller</c> suffix when
    /// generating a <c>Location</c> header.
    /// </summary>
    private static string ControllerName(ControllerBase controller)
    {
        const string suffix = "Controller";
        var name = controller.GetType().Name;

        return name.EndsWith(suffix, StringComparison.Ordinal)
            ? name[..^suffix.Length]
            : name;
    }

    private static IActionResult Failure(ControllerBase controller, Error error)
    {
        var status = ToStatusCode(error.Type);

        var response = ApiResponse.Failure(
            string.IsNullOrWhiteSpace(error.Message) ? "The request could not be completed." : error.Message,
            [new ApiError(error.Code, error.Message)],
            controller.HttpContext.TraceIdentifier);

        return status switch
        {
            StatusCodes.Status400BadRequest => controller.BadRequest(response),
            StatusCodes.Status401Unauthorized => controller.Unauthorized(response),
            StatusCodes.Status403Forbidden => controller.StatusCode(StatusCodes.Status403Forbidden, response),
            StatusCodes.Status404NotFound => controller.NotFound(response),
            StatusCodes.Status409Conflict => controller.Conflict(response),
            StatusCodes.Status422UnprocessableEntity => controller.UnprocessableEntity(response),
            _ => controller.StatusCode(status, response)
        };
    }

    private static int ToStatusCode(ErrorType type) =>
        type switch
        {
            ErrorType.Validation => StatusCodes.Status400BadRequest,
            ErrorType.Unauthorized => StatusCodes.Status401Unauthorized,
            ErrorType.Forbidden => StatusCodes.Status403Forbidden,
            ErrorType.NotFound => StatusCodes.Status404NotFound,
            ErrorType.Conflict => StatusCodes.Status409Conflict,
            ErrorType.Unexpected => StatusCodes.Status500InternalServerError,
            _ => StatusCodes.Status400BadRequest
        };
}